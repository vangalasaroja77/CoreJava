public class DisplayChar {

    static void main() {

        System.out.println("lower case letters");
        for(char ch='a';ch<='z';ch++)
        {
            System.out.print(ch+" ");
        }
        System.out.println();
        System.out.println("upper case letters");
        for(char ch='A';ch<='Z';ch++)
        {
            System.out.print(ch+" ");
        }
    }
}
